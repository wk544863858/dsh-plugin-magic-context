/**
 * D1 — fresh-machine bootstrap for the shared contract store.
 *
 * Distribution shape (decided 2026-10-12): this plugin ships as an offline npm
 * tarball to machines WITHOUT upstream Magic Context. On such a machine the
 * contract store (`context.db`) does not exist, and every opener before this
 * module would silently degrade: `new DatabaseSync(path)` creates a 0-byte
 * file, no `schema_migrations` means the fence never fires, and the first
 * prepared statement against `memories` fails — the whole memory lane dead
 * with no error row. The default-flip of `vectorBackfill` made the READ path
 * good by default; THIS module makes it work at all.
 *
 * Mechanism: `assets/contract-template.db` — the real v94 contract shape,
 * generated by `scripts/make-contract-template.mjs` (live store → VACUUM INTO
 * → data cleared → verified: its object digest equals the freeze baseline
 * `8bd1476f9a07…`, so a bootstrapped store is byte-shape-identical to what MC
 * itself would have migrated to). First run copies the template into place;
 * an EXISTING store — valid, foreign-shaped, or fenced — is never touched
 * (the writer's and bridge's existing refusals keep guarding those).
 */
import { copyFileSync, existsSync, mkdirSync, statSync } from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DatabaseSync } from 'node:sqlite'

export type ContractBootstrapOutcome =
  | 'exists' // a store is already there — hands off, whatever its shape
  | 'bootstrapped' // no file: template copied into place
  | 'repaired-empty' // a 0-byte file existed (a failed opener's residue): replaced
  | 'template-missing' // template not shipped — caller proceeds as before
  | 'failed' // copy or sanity check threw — caller proceeds as before

/** Two levels up from this module: src/core (dev/tests) and lib/core (build) both resolve to the package root. */
export function contractTemplatePath(): string {
  return fileURLToPath(new URL('../../assets/contract-template.db', import.meta.url))
}

/**
 * Make sure a usable contract store exists at `dbPath`. Idempotent, fail-open:
 * every non-`exists` outcome still lets the caller open the store and hit the
 * same refusals it would have hit before this module existed.
 */
export function ensureContractStore(dbPath: string): { outcome: ContractBootstrapOutcome; detail?: string } {
  try {
    const existed = existsSync(dbPath)
    if (existed && statSync(dbPath).size > 0) return { outcome: 'exists' }
    const template = contractTemplatePath()
    if (!existsSync(template)) return { outcome: 'template-missing', detail: template }
    mkdirSync(dirname(dbPath), { recursive: true })
    copyFileSync(template, dbPath)
    // Sanity: the copy must carry the contract's own version marker. If it
    // does not, the template is corrupt — report and let downstream refuse.
    let version: number | null | undefined
    const probe = new DatabaseSync(dbPath, { readOnly: true })
    try {
      const row = probe.prepare('SELECT MAX(version) AS v FROM schema_migrations').get() as
        | { v: number | null }
        | undefined
      version = row?.v
      if (version === undefined || version === null) {
        return { outcome: 'failed', detail: 'bootstrapped store has no schema_migrations version' }
      }
    } finally {
      probe.close()
    }
    return { outcome: existed ? 'repaired-empty' : 'bootstrapped', detail: `v${String(version)}` }
  } catch (error) {
    return { outcome: 'failed', detail: error instanceof Error ? error.message : String(error) }
  }
}
