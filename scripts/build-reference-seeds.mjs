#!/usr/bin/env node
/**
 * Regenerate `src/core/reference-seeds.ts` from upstream's calibration corpus.
 *
 *   node scripts/build-reference-seeds.mjs [--check] --upstream <magic-context checkout>
 *
 * Upstream ships 60 full scored digest examples
 * (`packages/plugin/src/hooks/magic-context/reference-seeds.generated.ts`) that its
 * historian reads as calibration anchors. The full blocks cost roughly 40x the
 * tokens of the signal they carry for our prompt, so this adapter keeps the scoring
 * signal — score, episode type, title, and the p3 tier — and drops the rest.
 *
 * The corpus belongs to the upstream project, not to this repository, so the
 * checkout must be named: `--upstream <dir>` or `MAGIC_CONTEXT_REPO`. This is a
 * maintainer step, run when upstream's corpus moves — not part of the gate.
 *
 * `--check` regenerates in memory and fails when the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const PKG = join(HERE, '..')

const argv = process.argv.slice(2)
const upstreamIndex = argv.indexOf('--upstream')
const UPSTREAM_REPO = upstreamIndex === -1 ? process.env.MAGIC_CONTEXT_REPO : argv[upstreamIndex + 1]
if (!UPSTREAM_REPO) {
  console.error('build-reference-seeds: the calibration corpus lives in upstream, not in this repository.')
  console.error('  pass --upstream <magic-context checkout>, or set MAGIC_CONTEXT_REPO.')
  process.exit(2)
}
const UPSTREAM = join(UPSTREAM_REPO, 'packages/plugin/src/hooks/magic-context/reference-seeds.generated.ts')
const TARGET = join(PKG, 'src/core/reference-seeds.ts')

const unescape = (text) => text.replace(/\\(n|r|t|'|"|\\)/g, (_all, code) => {
  switch (code) {
    case 'n': return '\n'
    case 'r': return '\r'
    case 't': return '\t'
    default: return code
  }
})

const squash = (text) => text.replace(/\s+/g, ' ').trim()

function extract() {
  const source = readFileSync(UPSTREAM, 'utf8')
  const anchors = []
  // The corpus mixes quoting styles: a block whose text carries single quotes is
  // emitted double-quoted (and vice versa), so both forms have to be accepted.
  const entry = /\{\s*importance:\s*(\d+),\s*block:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*,?\s*\}/gs
  for (const [, importance, singleQuoted, doubleQuoted] of source.matchAll(entry)) {
    const block = unescape(singleQuoted ?? doubleQuoted ?? '')
    const title = /title="([^"]*)"/.exec(block)?.[1]
    const episodeType = /episode_type="([^"]*)"/.exec(block)?.[1]
    const p3 = /<p3>\s*([\s\S]*?)\s*<\/p3>/.exec(block)?.[1]
    if (title === undefined || episodeType === undefined || p3 === undefined) {
      throw new Error(`reference-seeds: seed ${importance} is missing title/episode_type/p3`)
    }
    const gist = squash(p3)
    anchors.push({
      importance: Number(importance),
      title: squash(title),
      episodeType: squash(episodeType),
      // Every anchor rides on every historian call, so the gist is held to what
      // distinguishes a score, not to the whole tier.
      gist: gist.length <= 100 ? gist : `${gist.slice(0, 99).trimEnd()}…`,
    })
  }
  if (anchors.length === 0) throw new Error(`reference-seeds: no seeds parsed from ${UPSTREAM}`)
  anchors.sort((left, right) => right.importance - left.importance)
  return anchors
}

function render(anchors) {
  const rows = anchors.map(anchor =>
    `  { importance: ${String(anchor.importance)}, title: ${JSON.stringify(anchor.title)}, `
      + `episodeType: ${JSON.stringify(anchor.episodeType)}, gist: ${JSON.stringify(anchor.gist)} },`)
  return `/**
 * AUTO-GENERATED by \`scripts/build-reference-seeds.mjs\` from upstream
 * \`packages/plugin/src/hooks/magic-context/reference-seeds.generated.ts\`.
 * DO NOT EDIT BY HAND — regenerate with \`npm run build:seeds\` after an upstream
 * replay (and keep it in step with \`mc-test --full\`).
 *
 * Upstream ships ${String(anchors.length)} full scored digest examples as the historian's
 * calibration corpus. A full block costs roughly 40x the tokens of the signal it
 * carries here, so this module keeps the scoring signal — score, episode type,
 * title, and the p3 tier — which is what places a new digest on the same scale.
 */
export interface ReferenceAnchor {
  readonly importance: number
  readonly title: string
  readonly episodeType: string
  readonly gist: string
}

/** Highest score first: the scale runs from here down to the trivial spans. */
export const REFERENCE_ANCHORS: readonly ReferenceAnchor[] = [
${rows.join('\n')}
]
`
}

const anchors = extract()
const rendered = render(anchors)
if (process.argv.includes('--check')) {
  const current = readFileSync(TARGET, 'utf8')
  if (current.replace(/\r\n/g, '\n') !== rendered.replace(/\r\n/g, '\n')) {
    console.error('reference-seeds: src/core/reference-seeds.ts is stale — run npm run build:seeds')
    process.exit(1)
  }
  console.log(`reference-seeds: ${String(anchors.length)} anchors up to date`)
} else {
  writeFileSync(TARGET, rendered)
  console.log(`reference-seeds: wrote ${String(anchors.length)} anchors to src/core/reference-seeds.ts`)
}
